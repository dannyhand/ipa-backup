// Small shared dialog pieces. These are MainActivity extension functions.

/**
 * A scrolling list of real checkboxes (with "All" / "None" links), updating [checked] as they're
 * ticked. Used instead of the dialog builder's own multi-choice list, whose ticks didn't show on some
 * phones (rows flashed but nothing appeared checked).
 */
internal fun MainActivity.checkList(labels: List<String>, checked: BooleanArray, maxHeightFraction: Double = 0.5): View {
    val density = resources.displayMetrics.density
    val pad = (16 * density).toInt()
    val boxes = labels.mapIndexed { i, label ->
        MaterialCheckBox(this).apply {
            text = label
            isChecked = checked[i]
            setOnCheckedChangeListener { _, on -> checked[i] = on }
        }
    }
    val list = LinearLayout(this).apply {
        orientation = LinearLayout.VERTICAL
        setPadding(pad, 0, pad, 0)
        boxes.forEach { addView(it) }
    }
    val scroll = android.widget.ScrollView(this).apply { addView(list) }
    val links = LinearLayout(this).apply {
        orientation = LinearLayout.HORIZONTAL
        setPadding(pad / 2, 0, pad, 0)
        for ((label, value) in listOf("All" to true, "None" to false)) addView(
            com.google.android.material.button.MaterialButton(this@checkList, null, com.google.android.material.R.attr.borderlessButtonStyle).apply {
                text = label
                setOnClickListener { boxes.forEach { it.isChecked = value } }
            })
    }
    return LinearLayout(this).apply {
        orientation = LinearLayout.VERTICAL
        if (labels.size > 3) addView(links)
        addView(scroll, LinearLayout.LayoutParams(-1, minOf(
            (resources.displayMetrics.heightPixels * maxHeightFraction).toInt(),
            (labels.size * 52 * density).toInt() + pad)))
    }
}
